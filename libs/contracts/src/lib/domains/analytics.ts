import { z } from 'zod';
import { Id, IsoDateTime } from '../common';
import type { Endpoint } from '../endpoint';
import { named } from '../registry';

// Product analytics ----------------------------------------------------------------------------
// Product KPIs (activation, time to first allocation, weekly active owners, time to approve,
// auto-match rate). Separate from the audit trail: no amounts, names or free text.

/** Events the web app may send. */
export const CLIENT_ANALYTICS_EVENTS = ['session.started', 'page.viewed'] as const;
/** Events only the API records, from the commands that cause them (later phases emit them). */
export const SERVER_ANALYTICS_EVENTS = [
  'allocation.created',
  'budget.increase_decided',
  'budget.control_changed',
  'request.submitted',
  'approval.decided',
  'contribution.requested',
  'contribution.decided',
  'event.submitted',
  'actual.imported',
  'actual.matched',
  'tieout.signed_off',
] as const;
export const ANALYTICS_EVENTS = [...CLIENT_ANALYTICS_EVENTS, ...SERVER_ANALYTICS_EVENTS] as const;
export type AnalyticsEventName = (typeof ANALYTICS_EVENTS)[number];

/** A route template such as `/budgets/:budgetId`: no ids, numbers, emails or query strings. */
export const RouteTemplate = z
  .string()
  .max(120)
  .regex(/^\/[a-zA-Z0-9\-/:]*$/, 'Send the route template, without query or fragment.')
  .refine(
    (r) => r.split('/').every((s) => !/^[0-9a-f-]{16,}$/i.test(s) && !/\d{4,}/.test(s)),
    'Send the route template, not a path with ids.',
  )
  .describe('Route template of the page, e.g. /budgets/:budgetId.');

const eventBase = {
  id: Id.describe('Generated by the client; a retried event with the same id is stored once.'),
  occurredAt: IsoDateTime.optional().describe(
    'Client time; the server uses its own time when this is missing, more than a day old or in the future.',
  ),
};

export const ClientAnalyticsEvent = named(
  'ClientAnalyticsEvent',
  z
    .discriminatedUnion('name', [
      z.object({ ...eventBase, name: z.literal('session.started') }).strict(),
      z
        .object({
          ...eventBase,
          name: z.literal('page.viewed'),
          properties: z.object({ route: RouteTemplate }).strict(),
        })
        .strict(),
    ])
    .describe('A web event with exactly the properties its name allows.'),
);

export const RecordAnalyticsRequest = named(
  'RecordAnalyticsRequest',
  z
    .object({ events: z.array(ClientAnalyticsEvent).min(1).max(25) })
    .strict()
    .describe('A batch of product analytics events from the web app.'),
);
export type RecordAnalyticsRequest = z.infer<typeof RecordAnalyticsRequest>;

export const RecordAnalyticsResponse = named(
  'RecordAnalyticsResponse',
  z
    .object({
      accepted: z.int().min(0).describe('Events stored by this request.'),
      duplicates: z.int().min(0).describe('Events already stored earlier (same id).'),
    })
    .strict(),
);
export type RecordAnalyticsResponse = z.infer<typeof RecordAnalyticsResponse>;

export const analyticsEndpoints = {
  recordAnalyticsEvents: {
    operationId: 'recordAnalyticsEvents',
    method: 'post',
    path: '/api/analytics/events',
    summary: 'Record product analytics events for the signed-in user (retry-safe by event id)',
    tags: ['analytics'],
    auth: true,
    body: RecordAnalyticsRequest,
    response: { status: 202, schema: RecordAnalyticsResponse },
    errors: [400, 401, 403],
  },
} as const satisfies Record<string, Endpoint>;
