import * as s from '@bf/api/db';
import type { Db } from '@bf/api/db';
import {
  CURRENCY_EXPONENTS,
  generateFiscalYear,
  mapToGroupYear,
  type FiscalCalendarDefinition,
} from '@bf/domain';
import {
  calendarsData,
  categoriesData,
  costCentersData,
  DOA_MATRIX,
  doaLimitsData,
  fiscalYearId,
  headcountData,
  legalEntitiesData,
  membershipsData,
  orgUnitsData,
  peopleData,
  periodId,
  planVersionsData,
  ratesData,
  reasonCodesData,
  roleGrantsData,
  seedId,
  seedPeriodStatus,
  TENANTS,
  tenantsData,
  userById,
} from '@bf/seed';

const CURRENCY_NAMES: Record<string, string> = {
  USD: 'US dollar',
  EUR: 'Euro',
  GBP: 'Pound sterling',
  INR: 'Indian rupee',
  JPY: 'Japanese yen',
  KWD: 'Kuwaiti dinar',
};

/** Reference data: idempotent inserts with fixed ids (runs as the owner role). */
export async function seedReference(db: Db): Promise<void> {
  await db.transaction(async (tx) => {
    await tx
      .insert(s.currencies)
      .values(
        Object.entries(CURRENCY_EXPONENTS).map(([code, exponent]) => ({
          code,
          exponent,
          name: CURRENCY_NAMES[code] ?? code,
        })),
      )
      .onConflictDoNothing();
    await tx
      .insert(s.tenants)
      .values([...tenantsData])
      .onConflictDoNothing();
    await tx
      .insert(s.tenantSettings)
      .values([
        {
          tenantId: TENANTS.acme,
          reportingRateType: 'month_end',
          defaultIntercompanyMode: 'recharge_at_cost',
          alertThresholdsPct: [50, 80, 100],
        },
        {
          tenantId: TENANTS.globex,
          reportingRateType: 'monthly_average',
          defaultIntercompanyMode: 'block',
          alertThresholdsPct: [50, 80, 100],
        },
        {
          tenantId: TENANTS.sandbox,
          reportingRateType: 'month_end',
          defaultIntercompanyMode: 'block',
          alertThresholdsPct: [50, 80, 100],
        },
      ])
      .onConflictDoNothing();
    await tx
      .insert(s.featureFlags)
      .values([
        {
          id: seedId('65000000', 1),
          tenantId: TENANTS.acme,
          key: 'ai.auto_approve_within_policy',
          enabled: false,
        },
        {
          id: seedId('65000000', 2),
          tenantId: TENANTS.acme,
          key: 'cards.push_limits',
          enabled: false,
        },
      ])
      .onConflictDoNothing();

    // Calendars, fiscal years and periods (generated by the domain fiscal engine).
    const groupYears = new Map<string, { id: string; startDate: string; endDate: string }[]>();
    for (const cal of calendarsData) {
      const def = cal.def as FiscalCalendarDefinition;
      await tx
        .insert(s.fiscalCalendars)
        .values({
          id: cal.id,
          tenantId: cal.tenantId,
          name: cal.name,
          calendarType: def.type,
          startMonth: 'startMonth' in def ? def.startMonth : null,
          labelBy: 'labelBy' in def ? def.labelBy : null,
          groupCalendarId: cal.groupCalendarId,
        })
        .onConflictDoNothing();
      for (const year of cal.years) {
        const fy = generateFiscalYear(def, year);
        if (!fy.ok) throw new Error(fy.error.message);
        const id = fiscalYearId(cal.index, year);
        const group = cal.groupCalendarId
          ? mapToGroupYear(fy.value, groupYears.get(cal.groupCalendarId) ?? [])
          : null;
        await tx
          .insert(s.fiscalYears)
          .values({
            id,
            tenantId: cal.tenantId,
            fiscalCalendarId: cal.id,
            label: fy.value.label,
            startDate: fy.value.startDate,
            endDate: fy.value.endDate,
            groupFiscalYearId: group?.id ?? null,
            planRatesLockedAt: new Date('2026-01-01T00:00:00Z'),
          })
          .onConflictDoNothing();
        if (!cal.groupCalendarId)
          groupYears.set(cal.id, [
            ...(groupYears.get(cal.id) ?? []),
            { id, startDate: fy.value.startDate, endDate: fy.value.endDate },
          ]);
        await tx
          .insert(s.fiscalPeriods)
          .values(
            fy.value.periods.map((p) => ({
              id: periodId(cal.index, year, p.number),
              tenantId: cal.tenantId,
              fiscalYearId: id,
              fiscalCalendarId: cal.id,
              periodNumber: p.number,
              label: p.label,
              startDate: p.startDate,
              endDate: p.endDate,
              status: seedPeriodStatus(p.endDate),
            })),
          )
          .onConflictDoNothing();
      }
    }

    await tx
      .insert(s.legalEntities)
      .values([...legalEntitiesData])
      .onConflictDoNothing();
    await tx
      .insert(s.exchangeRates)
      .values(
        ratesData.map((r) => ({
          ...r,
          lockedAt: r.locked ? new Date('2026-01-01T00:00:00Z') : null,
        })),
      )
      .onConflictDoNothing();
    await tx
      .insert(s.orgUnits)
      .values(orgUnitsData.map((o) => ({ ...o, validFrom: '2026-01-01' })))
      .onConflictDoNothing();
    const closure: (typeof s.orgUnitClosure.$inferInsert)[] = [];
    for (const unit of orgUnitsData) {
      let cursor: (typeof orgUnitsData)[number] | undefined = unit;
      let depth = 0;
      while (cursor) {
        closure.push({
          id: seedId('34000000', closure.length + 1),
          tenantId: unit.tenantId,
          ancestorId: cursor.id,
          descendantId: unit.id,
          depth,
          validFrom: '2026-01-01',
        });
        const parentId: string | null = cursor.parentId;
        cursor = orgUnitsData.find((o) => o.id === parentId);
        depth++;
      }
    }
    await tx.insert(s.orgUnitClosure).values(closure).onConflictDoNothing();
    await tx
      .insert(s.costCenters)
      .values(costCentersData.map((c) => ({ ...c, validFrom: '2026-01-01' })))
      .onConflictDoNothing();
    await tx.insert(s.people).values(peopleData).onConflictDoNothing();
    await tx
      .insert(s.reportingLines)
      .values(
        (
          [
            ['regional-manager', 'ceo'],
            ['budget-owner', 'ceo'],
            ['department-head', 'ceo'],
            ['finance-admin', 'ceo'],
            ['finance-controller', 'finance-admin'],
            ['location-manager', 'regional-manager'],
            ['event-organizer', 'location-manager'],
            ['employee', 'location-manager'],
          ] as const
        ).map(([person, manager], i) => ({
          id: seedId('35000000', i + 1),
          tenantId: TENANTS.acme,
          personId: userById(person).personId!,
          managerPersonId: userById(manager).personId!,
          validFrom: '2026-01-01',
        })),
      )
      .onConflictDoNothing();
    await tx.insert(s.memberships).values(membershipsData).onConflictDoNothing();
    await tx
      .insert(s.roleGrants)
      .values(roleGrantsData as (typeof s.roleGrants.$inferInsert)[])
      .onConflictDoNothing();
    await tx.insert(s.budgetCategories).values(categoriesData).onConflictDoNothing();
    await tx.insert(s.reasonCodes).values(reasonCodesData).onConflictDoNothing();
    await tx
      .insert(s.planVersions)
      .values(
        planVersionsData.map((p) => ({
          ...p,
          approvedAt: p.status === 'approved' ? new Date('2026-01-05T00:00:00Z') : null,
          approvedBy: p.status === 'approved' ? userById('ceo').personId : null,
        })),
      )
      .onConflictDoNothing();
    await tx
      .insert(s.rolloverPolicies)
      .values([
        {
          id: seedId('66000000', 1),
          tenantId: TENANTS.acme,
          code: 'LAPSE',
          name: 'Lapse at year end',
          mode: 'lapse',
          sweepTo: 'parent',
        },
        {
          id: seedId('66000000', 2),
          tenantId: TENANTS.acme,
          code: 'CARRY-25',
          name: 'Carry up to 25%',
          mode: 'carry_capped',
          capBps: 2500,
          sweepTo: 'parent',
        },
      ])
      .onConflictDoNothing();
    await tx
      .insert(s.programTemplates)
      .values(
        (
          [
            ['PER-HEAD-ENGAGEMENT', 'Per-head engagement', 'per_head'],
            ['FESTIVAL', 'Festival celebration', 'fixed'],
            ['OFFSITE', 'Team offsite', 'fixed'],
            ['WELLBEING', 'Wellbeing program', 'per_head'],
            ['RECOGNITION', 'Recognition program', 'per_head'],
          ] as const
        ).map(([code, name, driver], i) => ({
          id: seedId('67000000', i + 1),
          tenantId: TENANTS.acme,
          code,
          name,
          kind: code.toLowerCase(),
          driver,
        })),
      )
      .onConflictDoNothing();
    await tx
      .insert(s.doaMatrixVersions)
      .values({
        id: DOA_MATRIX.acmeV1,
        tenantId: TENANTS.acme,
        version: 1,
        status: 'active',
        validFrom: '2026-01-01',
        approvedBy: userById('ceo').personId,
      })
      .onConflictDoNothing();
    await tx
      .insert(s.doaLimits)
      .values(
        doaLimitsData.map((d) => ({
          ...d,
          legalEntityId: null,
        })) as (typeof s.doaLimits.$inferInsert)[],
      )
      .onConflictDoNothing();
    await tx
      .insert(s.intercompanyPolicies)
      .values({
        id: seedId('68000000', 1),
        tenantId: TENANTS.acme,
        mode: 'recharge_at_cost',
        markupBps: 0,
        taxApproverPersonId: userById('finance-controller').personId,
        validFrom: '2026-01-01',
      })
      .onConflictDoNothing();
    await tx.insert(s.headcountSnapshots).values(headcountData.snapshot).onConflictDoNothing();
    await tx.insert(s.headcountSnapshotLines).values(headcountData.lines).onConflictDoNothing();
  });
}
